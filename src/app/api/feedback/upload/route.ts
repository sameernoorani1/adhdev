import { NextRequest, NextResponse } from 'next/server';
import { checkAdmin } from '@/lib/feedback/core';
import { getActiveProject, getProjectById, getProjectUploadsDir } from '@/lib/feedback/registry';
import fs from 'fs';
import path from 'path';

function getUploadsDir(projectId?: string | null): string {
    const project = getProjectById(projectId) || getActiveProject();
    if (project) return getProjectUploadsDir(project);
    return path.join(process.cwd(), 'public', 'feedback-images');
}

// AD-207 / AD-226: extension allowlist, organised by how the serve route
// returns each category. The serve route (api/uploads/[filename]) sets the
// matching MIME and adds X-Content-Type-Options: nosniff on every response,
// so a `.txt` cannot be MIME-sniffed into HTML. Code/text extensions are
// served as text/plain so they cannot execute via <script src=…>; binary
// docs and archives are served with Content-Disposition: attachment.
//
// Still rejected (not on this list): html/htm/xhtml/svg (browser renders
// inline → XSS), exe/dll/msi/bat/cmd/vbs/scr/com/app/dmg/pkg/apk/ipa
// (native executables), php/asp/aspx/jsp (server-side scripts).
const ALLOWED_UPLOAD_EXTENSIONS = new Set([
    // Inline-rendered: images, PDFs, markdown, plain text
    'jpg', 'jpeg', 'png', 'gif', 'webp', 'pdf', 'md', 'txt',
    // Code / structured text (served as text/plain)
    'js', 'ts', 'tsx', 'jsx', 'mjs', 'cjs',
    'py', 'go', 'rb', 'rs', 'java', 'c', 'h', 'cpp', 'hpp',
    'sh', 'bash', 'ps1', 'sql',
    'css', 'scss', 'less', 'xml',
    'json', 'jsonl', 'yaml', 'yml', 'toml', 'ini',
    'csv', 'tsv', 'log',
    // Office docs + archives (served with Content-Disposition: attachment)
    'doc', 'docx', 'xls', 'xlsx', 'ppt', 'pptx',
    'zip', 'tar', 'gz', 'tgz', '7z', 'rar',
]);

// POST — upload file to local public/feedback-images/
export async function POST(request: NextRequest) {
    const auth = await checkAdmin();
    if (!auth.authorized) return auth.error!;

    try {
        const formData = await request.formData();
        const file = formData.get('file') as File | null;

        if (!file) {
            return NextResponse.json({ error: 'No file provided' }, { status: 400 });
        }

        if (file.size > 20 * 1024 * 1024) {
            return NextResponse.json({ error: 'File too large (max 20MB)' }, { status: 400 });
        }

        // AD-207: enforce extension allowlist. The check is on the original
        // filename's extension; the on-disk filename is generated by us and
        // preserves the same extension below.
        const rawExt = (file.name.split('.').pop() || '').toLowerCase();
        if (!ALLOWED_UPLOAD_EXTENSIONS.has(rawExt)) {
            return NextResponse.json({
                error: `Unsupported file type: .${rawExt || '(none)'}. Allowed: ${[...ALLOWED_UPLOAD_EXTENSIONS].join(', ')}.`,
            }, { status: 400 });
        }

        // Ensure directory exists
        const projectId = request.headers.get('x-adhdev-project');
        const uploadsDir = getUploadsDir(projectId);
        if (!fs.existsSync(uploadsDir)) {
            fs.mkdirSync(uploadsDir, { recursive: true });
        }

        const ext = rawExt;
        const filename = `${Date.now()}_${Math.random().toString(36).slice(2, 8)}.${ext}`;
        const filePath = path.join(uploadsDir, filename);

        const buffer = Buffer.from(await file.arrayBuffer());
        fs.writeFileSync(filePath, buffer);

        const isImage = file.type.startsWith('image/');

        // AD-124: include the project id as a query param so <img src> tags
        // (which can't send custom headers) can still resolve the right uploads
        // dir when the active project differs from the board being viewed.
        const project = getProjectById(projectId) || getActiveProject();
        const url = project
            ? `/api/uploads/${filename}?project=${encodeURIComponent(project.id)}`
            : `/api/uploads/${filename}`;

        return NextResponse.json({
            url,
            filename: file.name,
            isImage,
            size: file.size,
            type: file.type,
        });
    } catch (err) {
        console.error('[ADHDev] POST /api/feedback/upload error:', err);
        return NextResponse.json({ error: 'Upload failed' }, { status: 500 });
    }
}
